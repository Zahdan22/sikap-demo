CREATE OR REPLACE FUNCTION public.submit_attendance_correction(p_actor uuid, p_user uuid, p_schedule integer, p_kind text, p_time timestamp with time zone, p_reason text, p_note text, p_evidence text)
 RETURNS uuid
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
declare s public.schedule%rowtype; role_name text; result_id uuid;
begin
 select role into role_name from public.users where id=p_actor and status_aktif;
 if role_name is null or role_name not in ('crew','manager','finance') or (role_name='crew' and p_actor<>p_user) then raise exception 'Akses koreksi ditolak.'; end if;
 if not exists(select 1 from public.users where id=p_user and role='crew' and status_aktif) then raise exception 'Crew tidak aktif.'; end if;
 select * into s from public.schedule where id=p_schedule and user_id=p_user for update;
 if not found or s.tanggal>(now() at time zone 'Asia/Jakarta')::date then raise exception 'Jadwal tidak valid atau berada di masa depan.'; end if;
 if p_time is null or p_time>now() or (p_time at time zone 'Asia/Jakarta')::date not between s.tanggal and s.tanggal+1
 or (p_kind='masuk' and (p_time at time zone 'Asia/Jakarta')::date<>s.tanggal) then raise exception 'Waktu koreksi tidak sesuai tanggal jadwal atau berada di masa depan.'; end if;
 if p_evidence not like p_user::text || '/%' or not exists(select 1 from storage.objects where bucket_id='attendance-corrections' and name=p_evidence) then raise exception 'Bukti koreksi wajib diunggah.'; end if;
 if p_kind='pulang' and not exists(select 1 from public.attendance where schedule_id=s.id and user_id=p_user and jam_masuk_aktual is not null) then raise exception 'Koreksi absen pulang membutuhkan check-in. Koreksi masuk terlebih dahulu.'; end if;
 if exists(select 1 from public.attendance_corrections where user_id=p_user and work_date=s.tanggal and kind=p_kind and status in ('pending','approved')) then raise exception 'Koreksi sejenis pada tanggal ini masih menunggu atau sudah disetujui.'; end if;
 insert into public.attendance_corrections(user_id,schedule_id,work_date,kind,requested_at,reason,note,evidence_path,submitted_by)
 values(p_user,s.id,s.tanggal,p_kind,p_time,p_reason,btrim(p_note),p_evidence,p_actor) returning id into result_id;
 insert into public.attendance_correction_events(correction_id,actor_id,action,after_value,note)
 values(result_id,p_actor,'submitted',jsonb_build_object('status','pending','time',p_time),btrim(p_note));
 return result_id;
end $function$
;
CREATE OR REPLACE FUNCTION public.guard_correction_payroll_revision()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
declare revision integer;
begin
 if tg_table_name='payroll_items' then
  select attendance_revision into revision from public.payroll_periods where id=new.payroll_period_id for share;
  if new.attendance_revision<>revision then raise exception 'Absensi sudah dikoreksi. Hitung dan simpan ulang draf payroll.'; end if;
 elsif new.status='finalized' and old.status<>'finalized' then
  if exists(select 1 from public.payroll_items where payroll_period_id=new.id and attendance_revision<>new.attendance_revision) then raise exception 'Ada koreksi absensi baru. Simpan ulang draf sebelum finalisasi.'; end if;
 end if;
 return new;
end $function$
;
CREATE OR REPLACE FUNCTION public.review_attendance_correction(p_actor uuid, p_id uuid, p_version integer, p_decision text, p_time timestamp with time zone, p_note text)
 RETURNS void
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
declare c public.attendance_corrections%rowtype; s public.schedule%rowtype; a public.attendance%rowtype;
 start_at timestamptz; end_at timestamptz; new_status text; late integer:=0; target_at timestamptz; old_at timestamptz;
 prior jsonb; result jsonb; sid integer;
begin
 if not exists(select 1 from public.users where id=p_actor and status_aktif and role in ('manager','finance')) then raise exception 'Akses khusus manager aktif.'; end if;
 if p_decision not in ('approved','rejected','cancelled') or p_decision is null or length(btrim(coalesce(p_note,''))) not between 1 and 1000 then raise exception 'Keputusan dan catatan manager wajib diisi.'; end if;
 -- Serialize with payroll finalization before touching attendance.
 lock table public.payroll_periods in share row exclusive mode;
 select schedule_id into sid from public.attendance_corrections where id=p_id;
 select * into s from public.schedule where id=sid for update;
 select * into c from public.attendance_corrections where id=p_id for update;
 if not found or c.version<>p_version then raise exception 'Pengajuan sudah berubah. Muat ulang halaman.'; end if;
 if c.status not in ('pending','approved') or (c.status='approved' and p_decision='rejected') then raise exception 'Status pengajuan sudah diproses.'; end if;
 if not (c.status='pending' and p_decision in ('rejected','cancelled')) and (s.id is null or s.user_id is distinct from c.user_id or s.tanggal<>c.work_date) then raise exception 'Jadwal crew telah berubah. Batalkan pengajuan dan buat ulang sesuai jadwal.'; end if;
 select * into a from public.attendance where schedule_id=s.id for update;
 if found and a.user_id<>c.user_id and (p_decision='approved' or (p_decision='cancelled' and c.status='approved')) then raise exception 'Pemilik absensi berbeda dari jadwal.'; end if;
 old_at:=case when c.kind='masuk' then a.jam_masuk_aktual else a.jam_pulang_aktual end;
 prior:=jsonb_build_object('status',c.status,'time',old_at,'attendance_status',case when c.kind='masuk' then a.status_masuk else a.status_pulang end,'late_minutes',a.menit_telat);
 if p_decision='approved' or (p_decision='cancelled' and c.status='approved') then
  if exists(select 1 from public.payroll_periods where status='finalized' and c.work_date between period_start and period_end) then raise exception 'Payroll periode ini sudah final. Koreksi tidak dapat mengubah arsip payroll final.'; end if;
  if c.status='approved' and old_at is distinct from c.effective_at then raise exception 'Absensi berubah di luar koreksi. Periksa data sebelum melanjutkan.'; end if;
  start_at:=(s.tanggal+s.jam_mulai) at time zone 'Asia/Jakarta';
  end_at:=(s.tanggal+s.jam_selesai) at time zone 'Asia/Jakarta';
  if end_at<=start_at then end_at:=end_at+interval '1 day'; end if;
  if p_decision='approved' then
   target_at:=p_time;
   if target_at is null or target_at>now() or (target_at at time zone 'Asia/Jakarta')::date not between s.tanggal and s.tanggal+1 then raise exception 'Jam koreksi tidak valid atau berada di masa depan.'; end if;
   if c.kind='masuk' then
    if target_at<start_at-interval '1 hour' or target_at>=end_at or (target_at at time zone 'Asia/Jakarta')::date<>s.tanggal then raise exception 'Jam masuk harus dalam rentang satu jam sebelum shift sampai sebelum shift berakhir.'; end if;
    if a.jam_pulang_aktual is not null and target_at>=a.jam_pulang_aktual then raise exception 'Jam masuk harus sebelum jam pulang.'; end if;
    if target_at<start_at-interval '9 minutes' then new_status:='tepat_waktu';
    else new_status:='telat'; late:=floor(extract(epoch from (target_at-(start_at-interval '9 minutes')))/60+0.5)::integer; end if;
   else
    if a.jam_masuk_aktual is null or target_at<=a.jam_masuk_aktual then raise exception 'Jam pulang harus setelah check-in.'; end if;
    if target_at<end_at then new_status:='lebih_awal';
    elsif target_at<=end_at+interval '45 minutes' then new_status:='tepat_waktu'; else new_status:='lewat_batas'; end if;
   end if;
   if not c.original_captured then
    c.original_at:=old_at;
    c.original_status:=coalesce(case when c.kind='masuk' then a.status_masuk else a.status_pulang end,'belum_absen');
    c.original_late:=coalesce(a.menit_telat,0);
    c.original_captured:=true;
   end if;
  else
   target_at:=c.original_at; new_status:=c.original_status; late:=c.original_late;
   if c.kind='masuk' and a.jam_pulang_aktual is not null and (target_at is null or target_at>=a.jam_pulang_aktual) then raise exception 'Batalkan koreksi pulang terlebih dahulu; hasil pemulihan masuk tidak cocok dengan jam pulang.'; end if;
   if c.kind='pulang' and target_at is not null and (a.jam_masuk_aktual is null or target_at<=a.jam_masuk_aktual) then raise exception 'Jam pulang asli tidak cocok dengan jam masuk saat ini.'; end if;
  end if;
  if a.id is null then
   insert into public.attendance(user_id,schedule_id) values(c.user_id,s.id) returning * into a;
  end if;
  if c.kind='masuk' then
   update public.attendance set jam_masuk_aktual=target_at,status_masuk=new_status,menit_telat=late where id=a.id;
  else
   update public.attendance set jam_pulang_aktual=target_at,status_pulang=new_status where id=a.id;
  end if;
  update public.payroll_periods set attendance_revision=attendance_revision+1 where status='draft' and c.work_date between period_start and period_end;
 end if;
 update public.attendance_corrections set status=p_decision,effective_at=case when p_decision='approved' then target_at else null end,
 original_at=c.original_at,original_status=c.original_status,original_late=c.original_late,original_captured=c.original_captured,
 reviewed_by=p_actor,reviewed_at=now(),manager_note=btrim(p_note),version=version+1 where id=c.id;
 result:=jsonb_build_object('status',p_decision,'time',case when p_decision='rejected' or (p_decision='cancelled' and c.status='pending') then old_at else target_at end,'attendance_status',new_status,'late_minutes',late);
 insert into public.attendance_correction_events(correction_id,actor_id,action,before_value,after_value,note)
 values(c.id,p_actor,case when p_decision='approved' and c.status='approved' then 'revised' else p_decision end,prior,result,btrim(p_note));
end $function$
