    raise exception 'Crew hanya dapat melaporkan kesalahannya sendiri tanpa mengisi poin atau denda.';
  end if;
  if p_tanggal is null or p_tanggal > (now() at time zone 'Asia/Jakarta')::date or p_kesalahan is null or length(trim(p_kesalahan))=0 then
    raise exception 'Isi tanggal kejadian yang valid dan keterangan kesalahan.';
  end if;
  if not exists(select 1 from public.users where id=p_user_id and role='crew') then raise exception 'Crew tidak ditemukan.'; end if;
  if v_manager and (p_poin is null or p_poin<0 or p_denda is null or p_denda<0 or p_denda>=1000000000000 or p_denda<>trunc(p_denda)) then
    raise exception 'Poin dan denda harus berupa angka bulat nol atau lebih.';
  end if;
  -- Same lock as overtime approval and payroll finalization.
  perform pg_advisory_xact_lock(20261011,1);
  if p_id is not null then
    select * into v_old from public.crew_violations where id=p_id and deleted_at is null for update;
    if not found then raise exception 'Laporan pelanggaran tidak ditemukan.'; end if;
    if p_version is distinct from v_old.version then raise exception 'Laporan sudah diubah manager lain. Muat ulang sebelum menyimpan.'; end if;
  end if;
  if exists(select 1 from public.payroll_periods where status='finalized'
    and (p_tanggal between period_start and period_end or v_old.tanggal between period_start and period_end)) then
    raise exception 'Payroll tanggal ini sudah difinalisasi. Laporan pelanggaran tidak dapat diubah.';
  end if;
  if p_id is null then
    insert into public.crew_violations(user_id,tanggal,kesalahan,poin,denda,created_by,reviewed_by,reviewed_at)
    values(p_user_id,p_tanggal,trim(p_kesalahan),coalesce(p_poin,0),coalesce(p_denda,0),auth.uid(),
      case when v_manager then auth.uid() end, case when v_manager then clock_timestamp() end) returning id into v_id;
  else
    update public.crew_violations set user_id=p_user_id,tanggal=p_tanggal,kesalahan=trim(p_kesalahan),poin=p_poin,denda=p_denda,
      reviewed_by=auth.uid(),reviewed_at=clock_timestamp(),updated_at=clock_timestamp(),version=version+1 where id=p_id returning id into v_id;
  end if;
  return v_id;
end;
$function$
