CREATE OR REPLACE FUNCTION public.save_jobdesk_preset(p_id bigint, p_nama text, p_jobdesk_ids bigint[])
 RETURNS bigint
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare v_id bigint;
begin
  if not exists (select 1 from public.users where id=auth.uid() and role='manager' and status_aktif) then
    raise exception 'Hanya manager penjadwalan aktif yang dapat mengatur preset jobdesk.';
  end if;
  if p_nama is null or length(trim(p_nama))=0 then raise exception 'Nama preset wajib diisi.'; end if;
  if p_jobdesk_ids is null or cardinality(p_jobdesk_ids) not between 1 and 5 then
    raise exception 'Pilih 1–5 jobdesk untuk satu sel jadwal.';
  end if;
  if (select count(distinct id) from unnest(p_jobdesk_ids) as ids(id)) <> cardinality(p_jobdesk_ids)
    or (select count(*) from public.jobdesk where id=any(p_jobdesk_ids)) <> cardinality(p_jobdesk_ids) then
    raise exception 'Pilihan jobdesk tidak valid atau berulang. Muat ulang daftar.';
  end if;
  if p_id is null then
    insert into public.jobdesk_preset(nama,dibuat_oleh) values(trim(p_nama),auth.uid()) returning id into v_id;
  else
    update public.jobdesk_preset set nama=trim(p_nama), updated_at=clock_timestamp() where id=p_id returning id into v_id;
    if not found then raise exception 'Preset tidak ditemukan. Muat ulang daftar.'; end if;
    delete from public.jobdesk_preset_item where preset_id=v_id;
  end if;
  insert into public.jobdesk_preset_item(preset_id,jobdesk_id,urutan)
  select v_id,id,(position-1)::integer from unnest(p_jobdesk_ids) with ordinality as ids(id,position);
  return v_id;
end;
