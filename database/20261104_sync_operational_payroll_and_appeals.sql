  reason text not null check (length(btrim(reason)) between 5 and 2000),
  evidence_path text,
  status text not null default 'pending' check (status in ('pending', 'approved', 'partially_approved', 'rejected', 'cancelled')),
  manager_note text,
  original_points integer not null check (original_points >= 0),
  original_fine numeric not null check (original_fine >= 0 and original_fine = trunc(original_fine)),
  resolved_points integer check (resolved_points is null or resolved_points >= 0),
  resolved_fine numeric check (resolved_fine is null or (resolved_fine >= 0 and resolved_fine = trunc(resolved_fine))),
  violation_version_at_request integer not null check (violation_version_at_request >= 1),
  responded_by uuid references public.users(id) on delete restrict,
  responded_at timestamptz,
  created_at timestamptz not null default clock_timestamp(),
  updated_at timestamptz not null default clock_timestamp(),
  check (
    (status in ('pending', 'cancelled') and responded_by is null and responded_at is null and manager_note is null and resolved_points is null and resolved_fine is null)
    or (status = 'approved' and responded_by is not null and responded_at is not null and manager_note is not null and resolved_points = 0 and resolved_fine = 0)
    or (status = 'partially_approved' and responded_by is not null and responded_at is not null and manager_note is not null and resolved_points is not null and resolved_fine is not null)
    or (status = 'rejected' and responded_by is not null and responded_at is not null and manager_note is not null and resolved_points is null and resolved_fine is null)
  )
