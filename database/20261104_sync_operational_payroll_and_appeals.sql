alter table public.payroll_tier_rates
  drop constraint if exists payroll_tier_rates_tier_check,
  add column if not exists label text,
  add column if not exists is_active boolean not null default true,
  add column if not exists supports_senior_plus boolean not null default false;

update public.payroll_tier_rates
set
  label = coalesce(nullif(btrim(label), ''), case tier
    when 'pra_training' then 'Pra-Training'
    when 'training' then 'Training'
    when 'junior' then 'Junior'
    when 'senior' then 'Senior'
    else initcap(replace(tier, '_', ' '))
  end),
  supports_senior_plus = case when tier = 'senior' then true else supports_senior_plus end;

alter table public.payroll_tier_rates
  alter column label set not null,
  add constraint payroll_tier_rates_code_check check (tier ~ '^[a-z][a-z0-9_]{1,47}$'),
  add constraint payroll_tier_rates_label_check check (char_length(btrim(label)) between 1 and 80);

create unique index if not exists payroll_tier_rates_one_active_senior_plus_idx
  on public.payroll_tier_rates (supports_senior_plus)
  where supports_senior_plus and is_active;

alter table public.payroll_senior_plus_rates
  drop constraint if exists payroll_senior_plus_rates_level_check,
  add column if not exists label text,
  add column if not exists is_active boolean not null default true;

